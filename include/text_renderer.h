#ifndef ATG_ENGINE_SIM_TEXT_RENDERER_H
#define ATG_ENGINE_SIM_TEXT_RENDERER_H

#include "render_math.h"

#include <algorithm>
#include <array>
#include <cctype>
#include <functional>
#include <memory>
#include <string>
#include <utility>
#include <vector>

class TextRenderer {
public:
    struct Run { float x, y, width, height; };

    TextRenderer();
    ~TextRenderer();
    bool loadFont(const std::string &path);

    // Scale applied to Silkscreen's normal-width (0.714em) advance. This is
    // intentionally user-tunable while retaining the font's relative glyph
    // widths (rather than forcing every character into one fixed cell).
    static constexpr float CharacterAdvance = 0.85f;
    // Preserve the source font's common left-side inset.
    static constexpr float LeftBearing = 0.12f;

    // A callback receives one complete string as horizontal bitmap-atlas runs.
    using RenderCallback = std::function<void(const std::vector<Run> &, const ysVector &)>;
    void SetColor(const ysVector &color) { m_color = color; }
    const ysVector &color() const { return m_color; }

    float CalculateWidth(const std::string &text, float height) const;
    void setRenderCallback(RenderCallback callback) { m_renderCallback = std::move(callback); }
    void RenderText(const std::string &text, float x, float y, float height);

private:
    struct FontData;
    std::unique_ptr<FontData> m_font;
    static constexpr float NormalAdvance = 0.7142857f;

    // The source font has individual advances; retaining them keeps aligned
    // dashboard labels from drifting like a monospaced replacement would.
    static constexpr float silkscreenAdvance(char character) {
        const char c = static_cast<char>(std::toupper(static_cast<unsigned char>(character)));
        switch (c) {
            case 'I': return 0.3571429f;
            case 'E': case 'F': case 'L': case 'T': case 'Z': case '1': return 0.5952381f;
            case 'M': case 'N': case 'V': case 'W': case 'X': case 'Y': return 0.8333333f;
            case ' ': return 0.4761905f;
            default: return NormalAdvance;
        }
    }

    static constexpr float characterAdvance(char character) {
        return CharacterAdvance * silkscreenAdvance(character) / NormalAdvance;
    }

    static std::array<unsigned char, 7> glyphRows(char character) {
        const char c = static_cast<char>(std::toupper(static_cast<unsigned char>(character)));
        switch (c) {
            case 'A': return { 0x0e,0x11,0x11,0x1f,0x11,0x11,0x11 };
            case 'B': return { 0x1e,0x11,0x11,0x1e,0x11,0x11,0x1e };
            case 'C': return { 0x0e,0x11,0x10,0x10,0x10,0x11,0x0e };
            case 'D': return { 0x1e,0x11,0x11,0x11,0x11,0x11,0x1e };
            case 'E': return { 0x1f,0x10,0x10,0x1e,0x10,0x10,0x1f };
            case 'F': return { 0x1f,0x10,0x10,0x1e,0x10,0x10,0x10 };
            case 'G': return { 0x0e,0x11,0x10,0x17,0x11,0x11,0x0f };
            case 'H': return { 0x11,0x11,0x11,0x1f,0x11,0x11,0x11 };
            case 'I': return { 0x0e,0x04,0x04,0x04,0x04,0x04,0x0e };
            case 'J': return { 0x07,0x02,0x02,0x02,0x12,0x12,0x0c };
            case 'K': return { 0x11,0x12,0x14,0x18,0x14,0x12,0x11 };
            case 'L': return { 0x10,0x10,0x10,0x10,0x10,0x10,0x1f };
            case 'M': return { 0x11,0x1b,0x15,0x15,0x11,0x11,0x11 };
            case 'N': return { 0x11,0x19,0x15,0x13,0x11,0x11,0x11 };
            case 'O': return { 0x0e,0x11,0x11,0x11,0x11,0x11,0x0e };
            case 'P': return { 0x1e,0x11,0x11,0x1e,0x10,0x10,0x10 };
            case 'Q': return { 0x0e,0x11,0x11,0x11,0x15,0x12,0x0d };
            case 'R': return { 0x1e,0x11,0x11,0x1e,0x14,0x12,0x11 };
            case 'S': return { 0x0f,0x10,0x10,0x0e,0x01,0x01,0x1e };
            case 'T': return { 0x1f,0x04,0x04,0x04,0x04,0x04,0x04 };
            case 'U': return { 0x11,0x11,0x11,0x11,0x11,0x11,0x0e };
            case 'V': return { 0x11,0x11,0x11,0x11,0x11,0x0a,0x04 };
            case 'W': return { 0x11,0x11,0x11,0x15,0x15,0x15,0x0a };
            case 'X': return { 0x11,0x11,0x0a,0x04,0x0a,0x11,0x11 };
            case 'Y': return { 0x11,0x11,0x0a,0x04,0x04,0x04,0x04 };
            case 'Z': return { 0x1f,0x01,0x02,0x04,0x08,0x10,0x1f };
            case '0': return { 0x0e,0x11,0x13,0x15,0x19,0x11,0x0e };
            case '1': return { 0x04,0x0c,0x04,0x04,0x04,0x04,0x0e };
            case '2': return { 0x0e,0x11,0x01,0x02,0x04,0x08,0x1f };
            case '3': return { 0x1e,0x01,0x01,0x0e,0x01,0x01,0x1e };
            case '4': return { 0x02,0x06,0x0a,0x12,0x1f,0x02,0x02 };
            case '5': return { 0x1f,0x10,0x10,0x1e,0x01,0x01,0x1e };
            case '6': return { 0x0e,0x10,0x10,0x1e,0x11,0x11,0x0e };
            case '7': return { 0x1f,0x01,0x02,0x04,0x08,0x08,0x08 };
            case '8': return { 0x0e,0x11,0x11,0x0e,0x11,0x11,0x0e };
            case '9': return { 0x0e,0x11,0x11,0x0f,0x01,0x01,0x0e };
            case '.': return { 0,0,0,0,0,0x06,0x06 };
            case ':': return { 0,0x06,0x06,0,0x06,0x06,0 };
            case '-': return { 0,0,0,0x1f,0,0,0 };
            case '+': return { 0,0x04,0x04,0x1f,0x04,0x04,0 };
            case '/': return { 0x01,0x02,0x02,0x04,0x08,0x08,0x10 };
            case '%': return { 0x19,0x19,0x02,0x04,0x08,0x13,0x13 };
            case '$': return { 0x04,0x0f,0x14,0x0e,0x05,0x1e,0x04 };
            case '(': return { 0x02,0x04,0x08,0x08,0x08,0x04,0x02 };
            case ')': return { 0x08,0x04,0x02,0x02,0x02,0x04,0x08 };
            case '[': return { 0x0e,0x08,0x08,0x08,0x08,0x08,0x0e };
            case ']': return { 0x0e,0x02,0x02,0x02,0x02,0x02,0x0e };
            case '<': return { 0x02,0x04,0x08,0x10,0x08,0x04,0x02 };
            case '>': return { 0x08,0x04,0x02,0x01,0x02,0x04,0x08 };
            case '=': return { 0,0x1f,0,0x1f,0,0,0 };
            case '!': return { 0x04,0x04,0x04,0x04,0x04,0,0x04 };
            case '?': return { 0x0e,0x11,0x01,0x02,0x04,0,0x04 };
            case '_': return { 0,0,0,0,0,0,0x1f };
            case ',': return { 0,0,0,0,0,0x06,0x04 };
            case '|': return { 0x04,0x04,0x04,0x04,0x04,0x04,0x04 };
            case '~': return { 0,0,0x09,0x16,0,0,0 };
            case '*': return { 0,0x15,0x0e,0x1f,0x0e,0x15,0 };
            case '@': return { 0x0e,0x11,0x17,0x15,0x17,0x10,0x0f };
            default: return { 0,0,0,0,0,0,0 };
        }
    }

    ysVector m_color = ysMath::Constants::One;
    RenderCallback m_renderCallback;
};

#endif /* ATG_ENGINE_SIM_TEXT_RENDERER_H */
